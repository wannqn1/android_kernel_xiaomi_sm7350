#!/usr/bin/env python3
"""Stage matched 6.18 kernel and DT artifacts for LineageOS."""

import collections
import os
import pathlib
import shutil
import subprocess
import sys
import tarfile
import tempfile


def index_modules(path):
    modules = collections.defaultdict(list)
    for module in sorted(path.rglob("*.ko")):
        modules[module.name].append(module)
    return modules


def stage_uapi_headers(root, out, stage):
    kernel = root / "redwood-6.18-kernel"
    modules = root / "redwood-6.18-modules"
    installed = stage / "usr"
    subprocess.run(
        [
            "make", "-s", "-C", kernel, f"O={out.resolve()}",
            "ARCH=arm64", "LLVM=1", f"INSTALL_HDR_PATH={installed.resolve()}",
            "headers_install",
        ],
        check=True,
    )

    vendor_roots = (
        "audio-kernel/include/uapi",
        "camera-kernel/include/uapi",
        "dataipa/drivers/platform/msm/include/uapi",
        "display-drivers/include/uapi",
        "graphics-kernel/include/uapi",
        "mm-drivers/sync_fence/include/uapi",
        "nfc-driver/include/uapi",
        "securemsm-kernel/include/uapi",
        "securemsm-kernel/smmu-proxy/include/uapi",
    )
    sanitizer_env = dict(os.environ, objtree=str(out.resolve()))
    for relative in vendor_roots:
        source = modules / relative
        headers = sorted(source.rglob("*.h"))
        if not headers:
            raise SystemExit(f"No UAPI headers found in {source}")
        for header in headers:
            destination = installed / "include" / header.relative_to(source)
            destination.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(
                [kernel / "scripts/headers_install.sh", header, destination],
                env=sanitizer_env,
                check=True,
            )

    # Bionic supplies compatibility versions of these headers.
    for header in ("asm/signal.h", "asm-generic/signal.h", "linux/eventpoll.h"):
        (installed / "include" / header).unlink()

    archive = stage / "kernel-uapi-headers.tar.gz"
    subprocess.run(
        [
            "tar", "--sort=name", "--mtime=@0", "--owner=0", "--group=0",
            "--numeric-owner", "-czf", archive, "-C", stage, "usr",
        ],
        check=True,
    )
    return archive


def write_uapi_blueprint(archive, output):
    with tarfile.open(archive, "r:gz") as bundle:
        paths = sorted(member.name for member in bundle if member.isfile())
    lines = [
        "// Generated by stage-renoir-kernel.py.",
        "genrule {",
        '    name: "renoir_kernel_uapi",',
        '    srcs: ["include/kernel-uapi-headers.tar.gz"],',
        '    cmd: "tar -xzf $(in) -C $(genDir)",',
        '    export_include_dirs: ["usr/include"],',
        "    out: [",
    ]
    lines.extend(f'        "{path}",' for path in paths)
    lines.extend(("    ],", "}", ""))
    output.write_text("\n".join(lines))


def main():
    if len(sys.argv) not in (3, 4) or sys.argv[3:] not in ([], ["--cvp"]):
        raise SystemExit("Usage: stage-renoir-kernel.py ROOT BUILD_DIR [--cvp]")
    root, work = map(pathlib.Path, sys.argv[1:3])
    cvp_test = len(sys.argv) == 4
    kernel = root / "redwood-6.18-kernel"
    out = work / "out"
    dt = work / ("dt-cvp" if cvp_test else "dt")
    destination = (work / "cvp-test" if cvp_test else root) / "device/xiaomi/renoir-kernel-6.18"
    release = (out / "include/config/kernel.release").read_text().strip()
    if not release.startswith("6.18.") or not release.endswith("-Tempest"):
        raise SystemExit(f"Expected a 6.18 Tempest build, got {release}")
    modules = index_modules(out)
    for name, paths in index_modules(work / "vb").items():
        modules[name].extend(paths)
    names = (kernel / "renoir/modules.load").read_text().splitlines()
    names = [line for line in names if line and not line.startswith("#")]
    if cvp_test:
        names.extend(("synx-driver.ko", "msm-cvp.ko"))
    if len(names) != len(set(names)):
        raise SystemExit("Duplicate entries in the Renoir module load list")
    missing = [name for name in names if name not in modules]
    ambiguous = [name for name in names if len(modules.get(name, [])) > 1]
    if missing or ambiguous:
        raise SystemExit(f"Missing modules {missing}\nAmbiguous modules {ambiguous}")

    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".renoir-stage-", dir=destination.parent) as tmp:
        stage = pathlib.Path(tmp)
        ramdisk = stage / "vendor_ramdisk"
        ramdisk.mkdir()
        for name in names:
            source = modules[name][0]
            vermagic = subprocess.check_output(
                ["modinfo", "-F", "vermagic", source], text=True
            ).split()
            if not vermagic or vermagic[0] != release:
                raise SystemExit(f"Unexpected vermagic for {source}: {vermagic}")
            subprocess.run(
                ["llvm-strip", "--strip-debug", "-o", ramdisk / name, source],
                check=True,
            )
        (ramdisk / "modules.load").write_text("\n".join(names) + "\n")
        shutil.copyfile(out / "arch/arm64/boot/Image", stage / "Image")
        shutil.copyfile(dt / "dtbo.img", stage / "dtbo.img")
        (stage / "dtb").mkdir()
        shutil.copyfile(dt / "shima.dtb", stage / "dtb/shima.dtb")

        target = stage / "lib/modules" / release
        target.parent.mkdir(parents=True)
        target.symlink_to(ramdisk, target_is_directory=True)
        for name in ("modules.builtin", "modules.builtin.modinfo"):
            shutil.copyfile(out / name, ramdisk / name)
        (ramdisk / "modules.order").write_text("\n".join(names) + "\n")
        depmod = subprocess.run(
            ["depmod", "-e", "-F", out / "System.map", "-b", stage, release],
            check=True,
            capture_output=True,
            text=True,
        )
        if "unknown symbol" in depmod.stderr or "disagrees about version" in depmod.stderr:
            raise SystemExit(depmod.stderr)
        dependencies = ramdisk / "modules.dep"
        indexed = {line.split(":", 1)[0] for line in dependencies.read_text().splitlines()}
        if indexed != set(names):
            raise SystemExit("depmod did not index the complete module set")

        headers = stage_uapi_headers(root, out, stage)
        destination.mkdir(exist_ok=True)
        headers_dir = destination / "headers/include"
        headers_dir.mkdir(parents=True, exist_ok=True)
        blueprint = stage / "Android.bp"
        write_uapi_blueprint(headers, blueprint)
        headers.replace(headers_dir / headers.name)
        blueprint.replace(headers_dir.parent / blueprint.name)
        for name in ["dtb", "vendor_ramdisk"]:
            previous = destination / name
            if previous.is_dir():
                shutil.rmtree(previous)
            shutil.move(stage / name, previous)
        for name in ["Image", "dtbo.img"]:
            (stage / name).replace(destination / name)
        print(f"Staged {release} and {len(names)} modules in {destination}")


if __name__ == "__main__":
    main()
